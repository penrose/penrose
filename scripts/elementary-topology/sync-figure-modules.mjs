/** Generate browser loaders only for published, reviewed figure programs. */
import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const root = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../..",
);
const inventory = JSON.parse(
  await readFile(
    path.join(root, "docs/elementary-topology/figures.json"),
    "utf8",
  ),
);
const originals = JSON.parse(
  await readFile(
    path.join(root, "docs/elementary-topology/original-illustrations.json"),
    "utf8",
  ),
);
const modules = [
  ...new Set(
    [...inventory.figures, ...originals.illustrations]
      .filter((figure) =>
        ["reviewed", "reviewed-original"].includes(figure.status),
      )
      .map((figure) => {
        assert(
          /^packages\/(bloom|examples)\/src\/(examples|elementary-topology)\/[\w-]+\.tsx?$/.test(
            figure.implementation,
          ),
          `Invalid module path for ${figure.id}`,
        );
        return `../../../${figure.implementation
          .replace(/^packages\//, "")
          .replace("/src/", "/dist/")
          .replace(/\.tsx?$/, ".js")}`;
      }),
  ),
].sort();
const content = await format(
  `// Generated by scripts/elementary-topology/sync-figure-modules.mjs.\n// Unreviewed example programs are deliberately outside the reader build.\nexport const figurePrograms: Record<string, () => Promise<unknown>> = {\n${modules
    .map(
      (module) =>
        `  ${JSON.stringify(module)}: () => import(${JSON.stringify(module)}),`,
    )
    .join("\n")}\n};\n`,
  { parser: "typescript" },
);
const target = path.join(
  root,
  "packages/docs-site/src/elementary-topology/figure-modules.generated.ts",
);
if (process.argv.includes("--check")) {
  assert.equal(
    await readFile(target, "utf8"),
    content,
    "Figure loaders are stale; run sync-figure-modules.mjs",
  );
  console.log(`Verified ${modules.length} reviewed program module loaders.`);
} else {
  await writeFile(target, content);
  console.log(`Updated ${modules.length} reviewed program module loaders.`);
}
